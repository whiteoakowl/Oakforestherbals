// Each driver exposes query(text, params) -> { rows, count }, exec(sql) for multi-statement
// scripts, and transaction(fn) where fn receives a handle with the same query/exec.
function postgresDriver(url) {
  const postgres = require('postgres');
  const toNumber = { to: 20, from: [20, 1700], serialize: String, parse: Number }; // bigint/numeric -> number
  const sql = postgres(url, {
    prepare: false, // required by Supabase's transaction pooler
    max: Number(process.env.DB_POOL_SIZE) || 3,
    idle_timeout: 20,
    connection: { TimeZone: 'UTC' },
    types: { bigint: toNumber },
    onnotice: () => {},
  });
  const wrap = (handle) => ({
    async query(text, params) {
      const rows = await handle.unsafe(text, params);
      return { rows: [...rows], count: rows.count };
    },
    exec: (text) => handle.unsafe(text), // no params -> simple protocol, multiple statements allowed
  });
  return {
    ...wrap(sql),
    transaction: (fn) => sql.begin((t) => fn(wrap(t))),
    end: () => sql.end(),
  };
}

function pgliteDriver(dataDir) {
  // Variable module names keep Netlify's bundler from packing this dev-only package (~35 MB).
  const pkg = '@electric-sql/pglite';
  const { PGlite } = require(pkg);
  const { citext } = require(`${pkg}/contrib/citext`);
  if (!dataDir.startsWith('memory://')) fs.mkdirSync(dataDir, { recursive: true });
  const pg = new PGlite(dataDir, { extensions: { citext } });
  const wrap = (handle) => ({
    async query(text, params) {
      const res = await handle.query(text, params);
      return { rows: res.rows, count: res.affectedRows || 0 };
    },
    exec: (text) => handle.exec(text),
  });
  return {
    ...wrap(pg),
    transaction: (fn) => pg.transaction((t) => fn(wrap(t))),
    end: () => pg.close(),
  };
}

const driver = process.env.DATABASE_URL
  ? postgresDriver(process.env.DATABASE_URL)
  : pgliteDriver(process.env.DB_PATH || path.join(__dirname, '..', 'data', 'pglite'));

// Creates tables on first use. The transaction-scoped lock keeps concurrent cold starts from
// racing each other (it also works through Supabase's transaction pooler).
const ready = (async () => {
  await driver.exec("SET TIME ZONE 'UTC'");
  await driver.transaction(async (t) => {
    await t.query('SELECT pg_advisory_xact_lock(72000)', []);
    await t.exec(SCHEMA);
  });
})();

// Queries are written with ? placeholders; Postgres wants $1, $2... (quoted strings are left alone).
function toPg(text) {
  let n = 0;
  let out = '';
  let quoted = false;
  for (const ch of text) {
    if (ch === "'") quoted = !quoted;
    out += ch === '?' && !quoted ? `$${++n}` : ch;
  }
  return out;
}

const txStore = new AsyncLocalStorage();

async function query(text, params) {
  await ready;
  const handle = txStore.getStore() || driver;
  return handle.query(toPg(text), params.map((p) => (p === undefined ? null : p)));
}

const all = async (text, ...params) => (await query(text, params)).rows;
const get = async (text, ...params) => (await query(text, params)).rows[0];
const run = async (text, ...params) => ({ changes: (await query(text, params)).count });
// INSERT that returns the new row's id.
const insert = async (text, ...params) => (await query(`${text} RETURNING id`, params)).rows[0].id;

// Runs fn inside a transaction; nested calls join the outer transaction.
async function tx(fn) {
  if (txStore.getStore()) return fn();
  await ready;
  return driver.transaction((handle) => txStore.run(handle, fn));
}

module.exports = { get, all, run, insert, tx, ready, end: () => driver.end() };
