'use strict';
// Versioned, forward-only schema migrations, applied in order after the base SCHEMA in db.js.
//
// Rules for adding one:
//  - Append to the end; never edit or reorder a migration that has shipped.
//  - Additive only (new tables, new nullable/defaulted columns, new indexes). Anything that
//    drops, renames or rewrites existing data needs explicit owner approval first.
//  - Each migration runs inside the boot transaction, under the schema advisory lock, and is
//    recorded in schema_migrations so it runs exactly once per database.
//  - Document it in docs/DATABASE.md and CHANGELOG.md.

