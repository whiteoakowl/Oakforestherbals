// Supabase publishes the public schema through its Data API (PostgREST) to anyone holding the
// project's publishable/anon key, and that key is designed to be public. A table with RLS off is
// readable and writable that way. The store reaches Postgres directly as the table owner, which
// bypasses RLS, so enabling RLS with no policies closes the Data API without affecting the app.
// Runs on every boot so tables added later are covered too.
const RLS_LOCKDOWN = `
DO $rls$
DECLARE t record;
BEGIN
  FOR t IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
           WHERE n.nspname = 'public' AND c.relkind = 'r' AND NOT c.relrowsecurity LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t.relname);
  END LOOP;
END
$rls$;
`;

// t: a transaction handle with query/exec (see db.js drivers).
async function migrate(t) {
  await t.exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
    id TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
  )`);
  const done = new Set((await t.query('SELECT id FROM schema_migrations', [])).rows.map((r) => r.id));
  for (const m of MIGRATIONS) {
    if (done.has(m.id)) continue;
    await t.exec(m.sql);
    await t.query('INSERT INTO schema_migrations (id) VALUES ($1)', [m.id]);
  }
  await t.exec(RLS_LOCKDOWN);
}

